-- Необязательно: ежедневный запуск сформировать_заявки() расширением pg_cron (листинг 3.5).
-- Требует установленного pg_cron и shared_preload_libraries = 'pg_cron' в postgresql.conf.
-- Если расширения нет, заявки формируются кнопкой «Сформировать заявки» в приложении.

CREATE EXTENSION pg_cron;
SELECT cron.schedule('сформировать_заявки', '0 7 * * *',
                     'CALL сформировать_заявки()');
