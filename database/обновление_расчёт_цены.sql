-- Обновление уже созданной базы: функция расчёта розничной стоимости
-- букета по составу — рекоменд_цена(растения[], количества[]).
-- Новой базе не нужен — функция уже есть в флористический_центр.sql.
-- Запуск (данные сохраняются, повторный запуск безопасен):
--   docker cp database florist-db:/
--   docker exec florist-db psql -U postgres -d florist -f /database/обновление_расчёт_цены.sql
-- =====================================================================
CREATE OR REPLACE FUNCTION рекоменд_цена(p_растения INT[], p_количества INT[]) RETURNS NUMERIC AS $$
    SELECT COALESCE(ROUND(SUM(t.количество * р.закупочная_цена * к.коэф_наценки), 2), 0)
    FROM unnest(p_растения, p_количества) AS t(растение_id, количество)
    JOIN растения  р ON р.id = t.растение_id
    JOIN категории к ON к.id = р.категория_id;
$$ LANGUAGE sql STABLE;
