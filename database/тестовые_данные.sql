-- ---------------------------------------------------------------------
-- Заказы
-- ---------------------------------------------------------------------
-- Прошлый год: по 3 заказа в месяц, кроме июля (в отчёте 5 будет нулевой месяц).
-- Текущий год: заказ раз в 8 дней с начала года до вчерашнего дня.
-- Клиент, флорист и способ оплаты чередуются; каждый третий заказ — с доставкой.
INSERT INTO заказы (дата, клиент_id, флорист_id, способ_оплаты, курьер_id,
                    адрес_доставки, время_доставки, получатель, телефон_получателя)
SELECT д.дата,
       (SELECT id FROM клиенты ORDER BY id OFFSET д.н % 8 LIMIT 1),
       (SELECT id FROM сотрудники WHERE должность = 'флорист' ORDER BY id OFFSET д.н % 3 LIMIT 1),
       (ARRAY['наличные', 'карта', 'перевод'])[1 + д.н % 3],
       CASE WHEN д.н % 3 = 0
            THEN (SELECT id FROM сотрудники WHERE должность = 'курьер' ORDER BY id OFFSET д.н % 2 LIMIT 1) END,
       CASE WHEN д.н % 3 = 0 THEN 'Москва, ул. Садовая, д. ' || (1 + д.н % 40) END,
       CASE WHEN д.н % 3 = 0 THEN д.дата + interval '3 hours' END,
       CASE WHEN д.н % 6 = 0 THEN 'Получатель ' || д.н END,
       CASE WHEN д.н % 6 = 0 THEN '+7926' || lpad(д.н::text, 7, '0') END
FROM (SELECT row_number() OVER (ORDER BY дата) AS н, дата
      FROM (SELECT date_trunc('year', now()) - interval '1 year'
                   + (м - 1) * interval '1 month' + д * interval '9 days' + interval '11 hours' AS дата
              FROM generate_series(1, 12) м, generate_series(0, 2) д
             WHERE м <> 7
            UNION ALL
            SELECT generate_series(date_trunc('year', now()) + interval '2 days 10 hours',
                                   now() - interval '1 day',
                                   interval '8 days')) даты
     ) д;

-- Букеты: в каждом заказе один букет, в каждом пятом — два.
-- Каждый четвёртый букет индивидуальный, остальные — по шаблону флориста заказа.
-- Цена продажи пока 0, ниже она ставится от рекомендуемой.
INSERT INTO букеты (заказ_id, шаблон_id, сложность, время_сборки, цена_продажи)
SELECT з.id,
       CASE WHEN (з.id + н) % 4 <> 0
            THEN (SELECT id FROM шаблоны WHERE флорист_id = з.флорист_id
                  ORDER BY id OFFSET (з.id + н) % 2 LIMIT 1) END,
       (ARRAY['простой', 'средний', 'сложный'])[1 + (з.id + н) % 3],
       (ARRAY[15, 30, 50])[1 + (з.id + н) % 3] + з.id % 10,
       0
FROM заказы з
CROSS JOIN LATERAL generate_series(1, CASE WHEN з.id % 5 = 0 THEN 2 ELSE 1 END) н
ORDER BY з.id, н;

-- Состав букетов по шаблону копируется из книги рецептов.
INSERT INTO состав_букета (букет_id, растение_id, количество)
SELECT б.id, сш.растение_id, сш.количество
FROM букеты б
JOIN состав_шаблона сш ON сш.шаблон_id = б.шаблон_id
ORDER BY б.id, сш.растение_id;

-- Индивидуальные букеты: примерно каждое пятое срезанное растение, по 3–7 штук.
INSERT INTO состав_букета (букет_id, растение_id, количество)
SELECT б.id, р.id, 3 + б.id % 5
FROM букеты б
JOIN растения р ON р.тип = 'срезанный' AND (р.id + б.id) % 5 = 0
WHERE б.шаблон_id IS NULL
ORDER BY б.id, р.id;

-- Цена продажи: рекомендуемая цена ± до 10 %, округлённая до 10 рублей.
UPDATE букеты
   SET цена_продажи = ROUND(рекоменд_цена(id) * (0.95 + (id % 3) * 0.05), -1);

-- Отдельные растения без оформления: в каждом третьем заказе — горшечное растение
-- (из первых трёх горшечных; Замиокулькас не продаётся).
INSERT INTO растения_в_заказе (заказ_id, растение_id, количество)
SELECT з.id,
       (SELECT id FROM растения WHERE тип = 'горшечный' ORDER BY id OFFSET з.id % 3 LIMIT 1),
       1 + з.id % 2
FROM заказы з
WHERE з.id % 3 = 1
ORDER BY з.id;

-- Статусы: заказы вручены в назначенное время (самовывоз — сразу), кроме
-- последнего заказа с доставкой (ещё у курьера) и последнего самовывоза
-- (клиент ещё не забрал) — чтобы на странице заказов были активные.
UPDATE заказы
   SET статус = 'вручён', время_вручения = COALESCE(время_доставки, дата)
 WHERE (курьер_id IS NULL, дата) NOT IN (SELECT курьер_id IS NULL, max(дата)
                                           FROM заказы GROUP BY курьер_id IS NULL);
UPDATE заказы SET статус = 'в доставке'
 WHERE статус = 'принят' AND курьер_id IS NOT NULL;

