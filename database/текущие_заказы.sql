-- =====================================================================
-- Текущие заказы «Флористического центра»: что сейчас в работе.
-- Выполняется после тестовых (и, если есть, дополнительных) данных.
--
-- 14 заказов относительно текущего момента:
--   «принят»     — 6 (доставка завтра и послезавтра днём, 2 самовывоза);
--   «в доставке» — 5 (курьер везёт, доставить в ближайшие часы);
--   «не вручён»  — 3 (курьер не застал получателя сегодня утром).
-- В каждом заказе один букет по шаблону флориста (шаблоны с запасом
-- на складе), в части заказов — ещё горшечное растение. Склад
-- списывает триггер тр_склад, статусы проверяет тр_статус_заказа.
-- Повторный запуск добавит ещё 14 таких заказов.
-- =====================================================================

BEGIN;

-- Шаблоны, всех растений которых на складе хотя бы впятеро больше нужного
CREATE TEMP TABLE запасные_шаблоны ON COMMIT DROP AS
SELECT row_number() OVER (ORDER BY ш.id) - 1 AS н, ш.id AS шаблон_id, ш.флорист_id
FROM шаблоны ш
WHERE EXISTS (SELECT 1 FROM состав_шаблона WHERE шаблон_id = ш.id)
  AND NOT EXISTS (SELECT 1 FROM состав_шаблона сш JOIN растения р ON р.id = сш.растение_id
                  WHERE сш.шаблон_id = ш.id AND р.остаток < сш.количество * 5);

CREATE TEMP TABLE тек ON COMMIT DROP AS
SELECT nextval('посл_заказы')::INT AS id, в.*,
       ш.шаблон_id, ш.флорист_id,
       (SELECT id FROM клиенты ORDER BY id
        OFFSET (в.н * 17) % (SELECT count(*) FROM клиенты) LIMIT 1) AS клиент_id,
       CASE WHEN в.адрес IS NOT NULL THEN
            (SELECT id FROM сотрудники WHERE должность = 'курьер' ORDER BY id
             OFFSET в.н % (SELECT count(*) FROM сотрудники WHERE должность = 'курьер') LIMIT 1) END AS курьер_id
FROM (VALUES
    -- н, оформлен (назад от сейчас), доставить к, статус, адрес, получатель, телефон.
    -- «Доставить к» для «в доставке» и «не вручён» — от начала текущего часа,
    -- для «принят» — от начала сегодняшнего дня (завтра и послезавтра в дневные часы).
    ( 1, interval '20 hours', interval '3 hours',  'в доставке', 'Москва, ул. Тверская, д. 18, кв. 41',           NULL,               NULL),
    ( 2, interval '6 hours',  interval '1 hour',   'в доставке', 'Москва, Ленинский пр-т, д. 32, офис 210',       'Ольга Викторовна', '+79161234567'),
    ( 3, interval '1 day',    interval '2 hours',  'в доставке', 'Москва, ул. Профсоюзная, д. 56, кв. 12',        NULL,               NULL),
    ( 4, interval '3 hours',  interval '2 hours',  'в доставке', 'Москва, Кутузовский пр-т, д. 9, кв. 87',        'Анна Сергеевна',   '+79037654321'),
    ( 5, interval '5 hours',  interval '4 hours',  'в доставке', 'Москва, ул. Мясницкая, д. 24, офис 5',          NULL,               NULL),
    ( 6, interval '1 day',    interval '-4 hours', 'не вручён',  'Москва, ул. Новый Арбат, д. 11, кв. 153',       'Игорь Павлович',   '+79265550123'),
    ( 7, interval '22 hours', interval '-3 hours', 'не вручён',  'Москва, Мичуринский пр-т, д. 7, кв. 64',        NULL,               NULL),
    ( 8, interval '1 day',    interval '-2 hours', 'не вручён',  'Москва, ул. Сретенка, д. 3, кв. 9',             'Мария Ивановна',   '+79857771122'),
    ( 9, interval '2 hours',  interval '1 day 10 hours', 'принят',     'Москва, ул. Большая Дмитровка, д. 7, кв. 30',   NULL,               NULL),
    (10, interval '1 hour',   interval '1 day 12 hours', 'принят',     'Москва, Цветной б-р, д. 15, кв. 8',             'Екатерина',        '+79169998877'),
    (11, interval '4 hours',  interval '1 day 15 hours', 'принят',     'Москва, ул. Покровка, д. 42, офис 12',          NULL,               NULL),
    (12, interval '30 minutes', interval '2 days 11 hours', 'принят',   'Москва, пр-т Мира, д. 102, кв. 215',            NULL,               NULL),
    (13, interval '2 hours',  NULL,                'принят',     NULL,                                            NULL,               NULL),
    (14, interval '40 minutes', NULL,              'принят',     NULL,                                            NULL,               NULL)
) AS в(н, назад, через, статус, адрес, получатель, телефон)
JOIN запасные_шаблоны ш ON ш.н = (в.н * 5) % (SELECT count(*) FROM запасные_шаблоны)
ORDER BY в.н;

INSERT INTO заказы (id, дата, клиент_id, флорист_id, способ_оплаты, курьер_id,
                    адрес_доставки, время_доставки, получатель, телефон_получателя)
SELECT т.id, now() - т.назад, т.клиент_id, т.флорист_id,
       (ARRAY['наличные', 'карта', 'перевод'])[1 + т.н % 3],
       т.курьер_id, т.адрес,
       CASE WHEN т.адрес IS NOT NULL
            THEN CASE WHEN т.статус = 'принят' THEN current_date::timestamp
                      ELSE date_trunc('hour', now()) END + т.через END,
       т.получатель, т.телефон
FROM тек т ORDER BY т.id;

-- Букет по шаблону флориста заказа; цена продажи — рекомендуемая, округлённая до 10 ₽
INSERT INTO букеты (заказ_id, шаблон_id, сложность, время_сборки, цена_продажи)
SELECT т.id, т.шаблон_id,
       (ARRAY['простой', 'средний', 'сложный'])[1 + т.н % 3],
       (ARRAY[20, 35, 55])[1 + т.н % 3] + т.н % 7,
       0
FROM тек т ORDER BY т.id;

INSERT INTO состав_букета (букет_id, растение_id, количество)
SELECT б.id, сш.растение_id, сш.количество
FROM тек т
JOIN букеты б ON б.заказ_id = т.id
JOIN состав_шаблона сш ON сш.шаблон_id = т.шаблон_id
ORDER BY б.id, сш.растение_id;

UPDATE букеты б SET цена_продажи = ROUND(рекоменд_цена(б.id), -1)
FROM тек т WHERE б.заказ_id = т.id;

-- В каждом третьем заказе — ещё горшечное растение (из тех, что есть на складе)
INSERT INTO растения_в_заказе (заказ_id, растение_id, количество)
SELECT т.id,
       (SELECT id FROM растения WHERE тип = 'горшечный' AND остаток >= 5 ORDER BY id
        OFFSET т.н % 3 LIMIT 1),
       1
FROM тек т
WHERE т.н % 3 = 0
  AND EXISTS (SELECT 1 FROM растения WHERE тип = 'горшечный' AND остаток >= 5)
ORDER BY т.id;

-- Статусы: «не вручён» бывает только после доставки
UPDATE заказы з SET статус = 'в доставке'
FROM тек т WHERE т.id = з.id AND т.статус IN ('в доставке', 'не вручён');
UPDATE заказы з SET статус = 'не вручён'
FROM тек т WHERE т.id = з.id AND т.статус = 'не вручён';

COMMIT;
